                <li><p>cebolla blanca, mediana, cortada en dados pequeños</p></li>
                <li><p>1 cucharada de perejil picado</p></li>
                <li><p>2 huevos</p></li>
                <li><p>  Aceite en spray</p></li>
                </ol>
                <h2>Instrucciones</h2>
                <p>1. Lava bien la papa y quítale la piel con un pelador de papas. Colócala en una olla con suficiente agua y agrega un punto de sal. Hiérvela durante unos 20 minutos, hasta que esté cocida, pero firme. Luego colócala en el refrigerador para que se enfríe, mientras preparas lo demás</p>
                <p>2. Cocina el arroz con tu método favorito, lo importante es que –una vez cocido- completes dos tazas. Si lo deseas, puedes tenerlo preparado desde el día anterior. </p>
                <p>3. Adoba los bistecs con el adobo. En un plato plano, extiende el pan rallado. Coloca 1/4 de taza de aceite en una sartén mediana, a fuego medio. Pasa los bistecs por el pan rallado, presionando cada lado hasta cubrirlos uniformemente. Cuando el aceite esté caliente, cocínalos durante 1 1/2 minutos de cada lado, o hasta que los extremos estén dorados. Ten cuidado con cocinarlos demasiado, ya que el pan rallado se dora con facilidad. </p>
                <p>4. Cuando estén listos, pásalos por una servilleta de papel para quitar el exceso de grasa. Mantenlos tibios. </p>
                <p>5. Lava y pica la cebolla en cubos pequeños y déjala a un lado. Abre la lata de tomates, escúrrelos en un colador y calcula 1 taza. </p>
                <p>6. Saca la papa del refrigerador y pícala en rodajas de 1/2 pulgada, aproximadamente. En un sartén anti-adherente, coloca el otro 1/4 de taza de aceite, a calentar a fuego medio alto. Cuando el aceite esté caliente, coloca las papas y fríelas durante aproximadamente dos minutos de cada lado, o hasta que estén doradas. Colócalas sobre servilletas de papel para absorber el aceite. </p>
                <p>7. Mientras fríes las papas, rocía con aceite en spray una sartén pequeña, y fríe los huevos a tu gusto, condimentando con sal y pimienta. </p>
                <p>8. Una vez listas las papas, el arroz, los bistecs, y los huevos, procede a armar el Silpancho. </p>
                <p>9. Coloca una taza de arroz extendida sobre un plato, luego el bistec, y luego el huevo frito. Alrededor, coloca los tomates y las cebollas en cubos y de un lado, agrega 3 a 4 rodajas de papas. Esparce perejil picado en cada plato y ¡buen provecho! </p>
