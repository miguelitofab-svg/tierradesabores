                <li><p>2 zanahorias peladas enteras en 4</p></li>
                <li><p>2 ajos enteros</p></li>
                <li><p>1 cebolla con cola</p></li>
                <li><p>6 papas runas grandes peladas (  con papa imilla se va evaporar rapido)</p></li>
                <li><p>1 taza de habas tiernas peladas</p></li>
                <li><p>Sal a gusto</p></li>
