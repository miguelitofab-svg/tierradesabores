                <h2>Instrucciones</h2>
                <p>1. Ponemos a hervir unos 500 gramos de carne para sopa en un cazo con 3 litros de agua.</p>
                <p>2. Al mismo tiempo ponemos a hervir el maní en otra olla con un poco de agua. Durante unos 5 minutos (este paso no es necesario para los cacahuetes ya tostados)</p>
                <p>3. Luego colocamos las nueces en una batidora de pie con aproximadamente un litro de agua. Pasados unos minutos ya tendremos lista nuestra salsa de maní. </p>
                <p>4. Tomamos 50 gramos de guisantes, preferiblemente frescos de la vaina como aquí, y los agregamos a la carne hirviendo. </p>
                <p>5. Con un rallador, picamos ahora el apio y las dos zanahorias y también cortamos la cebolla y el perejil en trozos pequeños.</p>
