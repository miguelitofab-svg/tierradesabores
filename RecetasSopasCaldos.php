                <h2>Instrucciones</h2>
                <p>1. Muchos preguntaron  porque NO hacer con pollo Parrillero? este pollo apenas tuvo 2-3 meses de vida  y  NO tiene sabor  y  llega cocer en 20 minutos.</p>
                <p>2. Nosotros recomendamos el POLLO criollo o  pollo que estuvo en producción de huevo, estos pollos  tiene mas de 9 meses de vida  como fueron pollos de postura (poner huevo)  son mas naturales  en su crecimiento y lo cual recomendamos, estos pollos lo venden en los mercados o abastos  en calidad de vivo la gallina roja o negra  que pone huevo. y en otros casos veras a las caceras que te lo venden pelado mas 4 bolivianos.</p>
                <p>3. Hacer cocer el pollo criollo en olla de presión  con agua 3/4 de la olla, para darle sabor puede echarlos las hojas de la cebolla o 2 zanahorias  y  1 cebolla   por se un pollo de mas de 9 meses es bien duro,  hacer cocer 25 minutos en máximo luego dejar en mínimo 15 minutos y apagar y luego esperar que enfrié la olla de presión.</p>
                <p>4. Aparte en una olla grande poner 3 tazas de AGUA, una vez tibia agregar las presas de pollo, pimienta las zanahorias el ajo la cebolla entera sin la cola</p>
                <p>5. Mientras se cocinan las presas de pollo lavar muy bien la cola de la cebolla, frotar con ambas manos hasta dejarla como papel, picar en tiras delgadas, dejar a un lado. Pelar las papas y dejarlas en una fuente cubierta con agua.</p>
                <p>6. Después de 25 minutos de cocción del pollo, agregar las papas peladas y dejar cocinar hasta que las papas y el pollo estén listos.</p>
                <p>7. HECHAR  de la olla de presión el caldo unas 3 tazas  o mas de acuerdo a lo que necesite servir  o  agua si es necesario.</p>
                <p>8.Aparte, en una olla pequeña con 1/2 taza de sopa, hacer pre-cocer las habas  para que queden verdes y la cola de la cebolla por 10 a 15 minutos o hasta que las habas queden tiernas.</p>
                <p>9.Una vez que las papas estén bien cocidas pero no desechas, retirar con cuidado junto con las presas de pollo, cubrirlas para mantenerlas calientes</p>
                <p>10. Para servir, acomodar una papa entera en cada plato, encima una presa de pollo, vierta el suficiente caldo caliente sobre la presa de pollo y la papa, cubrir todo con la cola de cebolla y las habas echarle perejil encima si  puede servirlo en platos de barro es mas RICO!.</p>
