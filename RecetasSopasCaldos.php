                <p>7. Finalmente añadimos 1-2 dientes de ajo prensado.</p>
                <p>8. En un mortero, triturar unos gramos de Comino en Grano, comino integral de Bolivia, en polvo y agregarlo a la sartén.</p>
                <p>9. Finalmente agregamos todo el contenido de la sartén a nuestra carne hirviendo con los guisantes, agregamos otras 2 cucharaditas de sal y dejamos que todo se cocine por unos minutos. En total (según el momento en que agregamos la carne al agua) nuestra Sopa de Maní debe cocinarse durante al menos 90 minutos..</p>
                <p>10. Para los fideos, agregue unos 300 gramos de espagueti en aceite caliente en otra sartén y fría los fideos hasta que estén dorados y crujientes.</p>
                <p>11. Para las patatas fritas, pelamos las patatas, aquí 6-7 patatas medianas, y las cortamos en patatas fritas del grosor y tamaño deseados. Luego lavamos un poco el almidón de las patatas, las dejamos escurrir bien y finalmente las freímos en un cazo con aceite caliente hasta que adquieran un bonito color.. </p>
                <p>12. Después de unos 90 minutos de tiempo de cocción, agregamos nuestra salsa de maní preparada y los fideos fritos a la olla. Los fideos se pueden partir en trozos pequeños.</p>
                <p>13. Ahora agregamos un buen puñado de orégano, removimos bien la sopa y ya casi terminamos.</p>
                <p>14. Después de unos minutos más de tiempo de cocción, ¡los platos se pueden servir! La sopa viene en un bol y finalmente se adorna con nuestras patatas fritas caseras.</p>
